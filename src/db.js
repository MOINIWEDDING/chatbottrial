// Base de datos PostgreSQL.
//  - Producción / Vercel: Supabase (u otro Postgres), vía DATABASE_URL.
//  - Desarrollo y pruebas: PGlite, un Postgres que corre dentro de Node y guarda los
//    datos en una carpeta local; no hay que instalar nada.
// Las consultas usan "?" como marcador de parámetro; se traducen a $1, $2… de Postgres.
const fs = require('node:fs');
const path = require('node:path');

const TABLES = ['users', 'sessions', 'tickets', 'messages', 'conversations'];

// Se ejecuta como un solo bloque (una transacción implícita). El candado evita que dos
// instancias de Vercel que arrancan a la vez creen las tablas al mismo tiempo.
const SCHEMA = `
SELECT pg_advisory_xact_lock(7310455);

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin', 'agent')),
  department text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
  token text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio text UNIQUE,
  channel text NOT NULL,
  contact_id text NOT NULL,
  contact_name text,
  reply_to text,
  department text NOT NULL,
  sector text NOT NULL,
  address text,
  latitude double precision,
  longitude double precision,
  description text NOT NULL,
  status text NOT NULL DEFAULT 'nueva',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_tickets_department ON tickets(department, status);
CREATE INDEX IF NOT EXISTS idx_tickets_sector ON tickets(sector);
CREATE INDEX IF NOT EXISTS idx_tickets_contact ON tickets(channel, contact_id);

CREATE TABLE IF NOT EXISTS messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id integer REFERENCES tickets(id) ON DELETE CASCADE,
  channel text NOT NULL,
  contact_id text NOT NULL,
  direction text NOT NULL CHECK (direction IN ('in', 'out', 'note', 'system')),
  external_id text UNIQUE,
  body text,
  attachments text,
  author_user_id integer REFERENCES users(id) ON DELETE SET NULL,
  delivery_error text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_messages_ticket ON messages(ticket_id);

CREATE TABLE IF NOT EXISTS conversations (
  channel text NOT NULL,
  contact_id text NOT NULL,
  state text NOT NULL,
  ticket_id integer REFERENCES tickets(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (channel, contact_id)
);

-- Supabase publica automáticamente las tablas del esquema "public" en su API REST.
-- Con RLS activado y sin políticas, nadie puede leerlas por esa vía (ni con la clave
-- "anon"); el servidor se conecta como dueño de las tablas y no se ve afectado.
${TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}
`;

// Si todas las tablas ya existen con RLS activado no se ejecuta SCHEMA, para no tomar
// candados sobre tablas en uso en cada arranque. (Para cambios futuros de estructura,
// agregue aquí una verificación de versión.)
const SCHEMA_READY = `
SELECT count(*)::int AS n FROM pg_class
WHERE relnamespace = 'public'::regnamespace AND relkind = 'r' AND relrowsecurity
  AND relname IN (${TABLES.map((t) => `'${t}'`).join(', ')})`;

/** Traduce los "?" de la consulta a $1, $2…, sin tocar los que estén dentro de comillas. */
function toPositional(sql) {
  let n = 0;
  return sql.replace(/'(?:[^']|'')*'|\?/g, (m) => (m === '?' ? `$${++n}` : m));
}

const isPostgresUrl = (url) => /^postgres(ql)?:\/\//.test(url ?? '');

/** true si el error es por un valor repetido en una columna única. */
const isUniqueViolation = (err) => err?.code === '23505';

/**
 * Opciones de conexión para pg. Supabase exige SSL; sus certificados los firma una CA
 * propia, así que se verifica con DATABASE_CA_CERT si se entrega (recomendado) y, si no,
 * se cifra la conexión sin verificar el certificado.
 */
function pgOptions(url, caCert) {
  const u = new URL(url);
  const local = ['localhost', '127.0.0.1', '::1'].includes(u.hostname);
  // El sslmode de la URL se maneja aquí: pg lo interpretaría como verificación estricta
  // y la conexión con Supabase fallaría sin la CA.
  u.searchParams.delete('sslmode');
  u.searchParams.delete('supa');
  let ssl = false;
  if (caCert) ssl = { ca: caCert.replace(/\\n/g, '\n'), rejectUnauthorized: true };
  else if (!local) ssl = { rejectUnauthorized: false };
  return { connectionString: u.toString(), ssl };
}

async function openPostgres({ url, caCert }) {
  const { Pool } = require('pg');
  // Pocas conexiones por instancia: en Vercel hay muchas instancias y el pooler de
  // Supabase (puerto 6543) es el que reparte las conexiones reales.
  const pool = new Pool({ ...pgOptions(url, caCert), max: 3, idleTimeoutMillis: 10_000, connectionTimeoutMillis: 10_000 });
  pool.on('error', (err) => console.error('Error en la conexión con la base de datos:', err.message));
  return {
    query: async (sql, args) => {
      const r = await pool.query(sql, args);
      return { rows: r.rows, changes: r.rowCount ?? 0 };
    },
    exec: (sql) => pool.query(sql),
    transaction: async (fn) => {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(async (sql, args) => {
          const r = await client.query(sql, args);
          return { rows: r.rows, changes: r.rowCount ?? 0 };
        });
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

async function openPglite({ url }) {
  const { PGlite } = require('@electric-sql/pglite');
  let dataDir;
  if (url && url !== ':memory:' && url !== 'memory://') {
    dataDir = path.resolve(url.replace(/^file:/, ''));
    fs.mkdirSync(dataDir, { recursive: true });
  }
  const lite = await PGlite.create(dataDir);
  const wrap = (runner) => async (sql, args) => {
    const r = await runner.query(sql, args);
    return { rows: r.rows, changes: r.affectedRows ?? 0 };
  };
  return {
    query: wrap(lite),
    exec: (sql) => lite.exec(sql),
    transaction: (fn) => lite.transaction((tx) => fn(wrap(tx))),
    close: () => lite.close(),
  };
}

/**
 * Abre la base de datos y crea las tablas si no existen.
 * url: "postgres://…" (Supabase) · ruta de una carpeta local · ":memory:".
 */
async function openDatabase({ url, caCert } = {}) {
  const driver = isPostgresUrl(url) ? await openPostgres({ url, caCert }) : await openPglite({ url });
  const { rows: [ready] } = await driver.query(SCHEMA_READY);
  if (ready.n !== TABLES.length) await driver.exec(SCHEMA);

  const run = async (q, sql, args) => q(toPositional(sql), args);
  return {
    kind: isPostgresUrl(url) ? 'postgres' : 'pglite',
    /** Primera fila del resultado (o undefined). */
    get: async (sql, ...args) => (await run(driver.query, sql, args)).rows[0],
    /** Todas las filas del resultado. */
    all: async (sql, ...args) => (await run(driver.query, sql, args)).rows,
    /** Ejecuta una instrucción; devuelve { changes, rows } (rows sirve con RETURNING). */
    run: async (sql, ...args) => run(driver.query, sql, args),
    /** Varias instrucciones en una transacción; recibe [[sql, ...args], …]. */
    batch: (statements) => driver.transaction(async (q) => {
      const results = [];
      for (const [sql, ...args] of statements) results.push(await run(q, sql, args));
      return results;
    }),
    close: () => driver.close(),
  };
}

module.exports = { openDatabase, isPostgresUrl, isUniqueViolation, toPositional, pgOptions };
